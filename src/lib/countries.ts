export const DEFAULT_COUNTRY_ISO2 = 'IN';

export function findCountry(iso2OrName?: string | null): Country | null {
  if (!iso2OrName) return null;
  const trimmed = iso2OrName.trim().toLowerCase();
  return (
    COUNTRIES.find(
      c => c.iso2.toLowerCase() === trimmed || c.name.toLowerCase() === trimmed
    ) || null
  );
}

export function findCountryByDialCode(dialCode?: string | null): Country | null {
  if (!dialCode) return null;
  const cleaned = dialCode.startsWith('+') ? dialCode : '+' + dialCode;
  return COUNTRIES.find(c => c.dialCode === cleaned) || null;
}
